def clean_text(
    text: Any,
) -> str:
    """
    Convert a value to clean display text.
    """

    if text is None:
        return ""

    return str(text).strip()


def add_text_box(
    slide,
    text: str,
    x: float,
    y: float,
    width: float,
    height: float,
    font_size: float = BODY_FONT_SIZE,
    bold: bool = False,
    align=PP_ALIGN.LEFT,
    vertical_anchor=MSO_ANCHOR.TOP,
):
    """
    Add a text box to a slide.

    Coordinates are in inches.
    """

    textbox = slide.shapes.add_textbox(
        Inches(x),
        Inches(y),
        Inches(width),
        Inches(height),
    )

    text_frame = textbox.text_frame

    text_frame.clear()

    text_frame.word_wrap = True
    text_frame.vertical_anchor = vertical_anchor

    paragraph = text_frame.paragraphs[0]

    paragraph.alignment = align

    run = paragraph.add_run()

    run.text = clean_text(text)

    run.font.size = Pt(font_size)
    run.font.bold = bold

    return textbox


def add_title(
    slide,
    title: str,
    slide_width: float,
):
    """
    Add a slide title.
    """

    return add_text_box(
        slide=slide,
        text=title,
        x=MARGIN_X,
        y=TITLE_Y,
        width=slide_width - (2 * MARGIN_X),
        height=TITLE_HEIGHT,
        font_size=TITLE_FONT_SIZE,
        bold=True,
    )


def add_bullet_list(
    slide,
    points: List[str],
    x: float,
    y: float,
    width: float,
    height: float,
    font_size: float = BODY_FONT_SIZE,
):
    """
    Add a bullet list to a slide.
    """

    textbox = slide.shapes.add_textbox(
        Inches(x),
        Inches(y),
        Inches(width),
        Inches(height),
    )

    text_frame = textbox.text_frame

    text_frame.clear()
    text_frame.word_wrap = True

    for index, point in enumerate(points):

        point = clean_text(point)

        if not point:
            continue

        if index == 0:
            paragraph = text_frame.paragraphs[0]
        else:
            paragraph = text_frame.add_paragraph()

        paragraph.text = point
        paragraph.font.size = Pt(font_size)

        paragraph.level = 0

        # python-pptx bullet behavior varies by version/theme.
        # Setting the paragraph text and level allows the template's
        # bullet formatting to be used when available.

    return textbox


