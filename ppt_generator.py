def build_image_catalog(
    plan: Dict[str, Any],
) -> Dict[str, Dict[str, Any]]:
    """
    Build an image lookup table.

    Expected presentation plan format:

        {
            "images": [
                {
                    "image_id": "...",
                    "path": "...",
                    ...
                }
            ]
        }

    Also supports images nested under a document object.
    """

    images = plan.get("images", [])

    if not images:

        document = plan.get("document", {})

        if isinstance(document, dict):
            images = document.get("images", [])

    catalog = {}

    for image in images:

        if not isinstance(image, dict):
            continue

        image_id = image.get("image_id")

        if image_id:
            catalog[str(image_id)] = image

    return catalog


def find_visual_for_slide(
    visual: Any,
    image_catalog: Dict[str, Dict[str, Any]],
) -> Optional[Dict[str, Any]]:
    """
    Resolve a visual reference from the AI presentation plan.

    Supports:

        "page_4_image_1"

    or:

        {
            "image_id": "page_4_image_1",
            "reason": "..."
        }
    """

    if isinstance(visual, str):

        return image_catalog.get(visual)

    if isinstance(visual, dict):

        image_id = (
            visual.get("image_id")
            or visual.get("id")
        )

        if image_id:
            return image_catalog.get(str(image_id))

    return None


# ---------------------------------------------------------------------------
# SLIDE CONTENT EXTRACTION
# ---------------------------------------------------------------------------

def get_slide_title(
    slide_plan: Dict[str, Any],
) -> str:
    """
    Get the slide title from a slide plan.
    """

    return clean_text(
        slide_plan.get("title")
        or slide_plan.get("slide_title")
        or f"Slide {slide_plan.get('slide_number', '')}"
    )


def get_slide_points(
    slide_plan: Dict[str, Any],
) -> List[str]:
    """
    Get the main bullet/key-point content.
    """

    points = (
        slide_plan.get("key_points")
        or slide_plan.get("bullet_points")
        or slide_plan.get("points")
        or []
    )

    if isinstance(points, str):
        return [points]

    return [
        clean_text(point)
        for point in points
        if clean_text(point)
    ]


def get_slide_visuals(
    slide_plan: Dict[str, Any],
) -> List[Any]:
    """
    Get visual references from a slide plan.
    """

    visuals = (
        slide_plan.get("visuals")
        or slide_plan.get("images")
        or []
    )

    if isinstance(visuals, (str, dict)):
        visuals = [visuals]

    return visuals


# ---------------------------------------------------------------------------
# SLIDE TYPE DETECTION
# ---------------------------------------------------------------------------

def get_slide_type(
    slide_plan: Dict[str, Any],
) -> str:
    """
    Determine how a slide should be rendered.

    Supported types:

        title
        content
        visual
        two_column
        quote
        section
    """

    slide_type = slide_plan.get("slide_type")

    if slide_type:
        return str(slide_type).lower()

    # Backward-compatible aliases.
    slide_type = slide_plan.get("layout")

    if slide_type:
        return str(slide_type).lower()

    # Infer a reasonable default.
    visuals = get_slide_visuals(slide_plan)
    points = get_slide_points(slide_plan)

    if visuals and not points:
        return "visual"

    return "content"


