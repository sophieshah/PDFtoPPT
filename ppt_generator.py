"""
ppt_generator.py

Render a presentation_plan.json into a PowerPoint presentation.

Pipeline:

    PDF
      |
      v
    pdf_extractor.py
      |
      v
    chunking.py
      |
      v
    presentation_ai.py
      |
      v
    presentation_plan.json
      |
      v
    ppt_generator.py
      |
      v
    PowerPoint

Responsibilities:
    1. Load the presentation plan.
    2. Load the PowerPoint template.
    3. Create slides from the AI-generated plan.
    4. Insert titles, key points, and visuals.
    5. Preserve PDF image provenance.
    6. Save the final .pptx.

Dependencies:
    pip install python-pptx
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from pptx import Presentation
from pptx.enum.shapes import MSO_SHAPE_TYPE
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
from pptx.util import Inches, Pt


# ---------------------------------------------------------------------------
# DEFAULT PRESENTATION SETTINGS
# ---------------------------------------------------------------------------

DEFAULT_WIDTH = 13.333
DEFAULT_HEIGHT = 7.5

MARGIN_X = 0.65
TITLE_Y = 0.35
TITLE_HEIGHT = 0.65

CONTENT_Y = 1.25
CONTENT_HEIGHT = 5.55

BODY_FONT_SIZE = 22
TITLE_FONT_SIZE = 30

IMAGE_GAP = 0.30

SUPPORTED_IMAGE_EXTENSIONS = {
    ".png",
    ".jpg",
    ".jpeg",
    ".bmp",
    ".gif",
    ".tif",
    ".tiff",
}


# ---------------------------------------------------------------------------
# FILE / JSON HELPERS
# ---------------------------------------------------------------------------

def load_json(path: str) -> Dict[str, Any]:
    """
    Load a JSON file.

    Args:
        path:
            Path to JSON file.

    Returns:
        Parsed JSON dictionary.
    """

    path = os.path.abspath(path)

    if not os.path.exists(path):
        raise FileNotFoundError(
            f"JSON file not found: {path}"
        )

    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def load_presentation_plan(
    plan_path: str,
) -> Dict[str, Any]:
    """
    Load a presentation plan generated by presentation_ai.py.
    """

    plan = load_json(plan_path)

    if not isinstance(plan, dict):
        raise ValueError(
            "Presentation plan must be a JSON object."
        )

    if "slides" not in plan:
        raise ValueError(
            "Presentation plan does not contain a 'slides' field."
        )

    if not isinstance(plan["slides"], list):
        raise ValueError(
            "Presentation plan 'slides' must be a list."
        )

    return plan


