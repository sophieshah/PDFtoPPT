def resolve_image_path(
    image: Dict[str, Any],
    plan_path: Optional[str] = None,
    image_root: Optional[str] = None,
) -> Optional[Path]:
    """
    Resolve the path to a PDF-extracted image.

    Search order:

        1. Absolute path stored in image metadata.
        2. Path relative to presentation plan.
        3. Path relative to image_root.
        4. Filename relative to image_root.
    """

    raw_path = image.get("path")

    if not raw_path:
        return None

    path = Path(raw_path)

    # Absolute path.
    if path.is_absolute() and path.exists():
        return path

    # Relative to the presentation plan.
    if plan_path:

        plan_directory = Path(plan_path).resolve().parent

        candidate = plan_directory / path

        if candidate.exists():
            return candidate

    # Relative to image root.
    if image_root:

        root = Path(image_root)

        candidate = root / path

        if candidate.exists():
            return candidate

        candidate = root / path.name

        if candidate.exists():
            return candidate

    # Relative to current working directory.
    if path.exists():
        return path.resolve()

    return None


def _image_size(
    image_path: Path,
) -> Tuple[int, int]:
    """
    Get image dimensions.

    Uses Pillow when available.

    Falls back to (1, 1) so the image can still be inserted.
    """

    try:
        from PIL import Image

        with Image.open(image_path) as img:
            return img.size

    except Exception:
        return 1, 1


def add_image_contain(
    slide,
    image_path: Path,
    x: float,
    y: float,
    width: float,
    height: float,
):
    """
    Add an image while preserving its aspect ratio.

    The entire image fits inside the supplied rectangle.
    """

    image_width, image_height = _image_size(
        image_path
    )

    if image_width <= 0 or image_height <= 0:
        return None

    image_ratio = image_width / image_height
    box_ratio = width / height

    if image_ratio > box_ratio:

        # Image is relatively wide.
        final_width = width
        final_height = width / image_ratio

        final_x = x
        final_y = y + (height - final_height) / 2

    else:

        # Image is relatively tall.
        final_height = height
        final_width = height * image_ratio

        final_x = x + (width - final_width) / 2
        final_y = y

    return slide.shapes.add_picture(
        str(image_path),
        Inches(final_x),
        Inches(final_y),
        width=Inches(final_width),
        height=Inches(final_height),
    )


def add_image_cover(
    slide,
    image_path: Path,
    x: float,
    y: float,
    width: float,
    height: float,
):
    """
    Add an image filling the supplied rectangle.

    The image is cropped as necessary to preserve aspect ratio.

    This is useful for photographic visuals.
    """

    image_width, image_height = _image_size(
        image_path
    )

    if image_width <= 0 or image_height <= 0:
        return None

    image_ratio = image_width / image_height
    box_ratio = width / height

    if image_ratio > box_ratio:

        # Image is too wide.
        final_height = height
        final_width = height * image_ratio

        final_x = x - (final_width - width) / 2
        final_y = y

    else:

        # Image is too tall.
        final_width = width
        final_height = width / image_ratio

        final_x = x
        final_y = y - (final_height - height) / 2

    return slide.shapes.add_picture(
        str(image_path),
        Inches(final_x),
        Inches(final_y),
        width=Inches(final_width),
        height=Inches(final_height),
    )


