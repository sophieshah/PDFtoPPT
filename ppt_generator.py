# ---------------------------------------------------------------------------
# MAIN SLIDE RENDERER
# ---------------------------------------------------------------------------

def render_slide(
    prs: Presentation,
    slide_plan: Dict[str, Any],
    image_catalog: Dict[str, Dict[str, Any]],
    plan_path: str,
    image_root: Optional[str] = None,
):
    """
    Render one slide based on its slide_type.
    """

    slide_type = get_slide_type(
        slide_plan
    )

    if slide_type in {
        "title",
        "title_slide",
    }:

        return render_title_slide(
            prs,
            slide_plan,
        )

    if slide_type in {
        "visual",
        "image",
        "visual_focus",
    }:

        return render_visual_slide(
            prs,
            slide_plan,
            image_catalog,
            plan_path,
            image_root,
        )

    if slide_type in {
        "two_column",
        "two-column",
        "comparison",
    }:

        return render_two_column_slide(
            prs,
            slide_plan,
        )

    if slide_type in {
        "quote",
        "highlight",
    }:

        return render_quote_slide(
            prs,
            slide_plan,
        )

    if slide_type in {
        "section",
        "section_divider",
        "divider",
    }:

        return render_section_slide(
            prs,
            slide_plan,
        )

    # Default.
    return render_content_slide(
        prs,
        slide_plan,
        image_catalog,
        plan_path,
        image_root,
    )


# ---------------------------------------------------------------------------
# PRESENTATION VALIDATION
# ---------------------------------------------------------------------------

def validate_plan_for_generation(
    plan: Dict[str, Any],
) -> List[str]:
    """
    Validate the minimum information needed to generate slides.

    Returns:
        List of warnings/errors.
    """

    problems = []

    slides = plan.get("slides")

    if not isinstance(slides, list):
        problems.append(
            "Presentation plan does not contain a valid slides list."
        )

        return problems

    if len(slides) == 0:
        problems.append(
            "Presentation plan contains no slides."
        )

    for index, slide in enumerate(slides, start=1):

        if not isinstance(slide, dict):

            problems.append(
                f"Slide {index} is not a JSON object."
            )

            continue

        if not get_slide_title(slide):

            problems.append(
                f"Slide {index} has no title."
            )

    return problems


# ---------------------------------------------------------------------------
# GENERATE PRESENTATION
# ---------------------------------------------------------------------------

def generate_presentation(
    plan_path: str,
    output_path: str,
    template_path: Optional[str] = None,
    image_root: Optional[str] = None,
    clear_template_slides: bool = True,
) -> str:
    """
    Generate a PowerPoint from a presentation plan.

    Args:
        plan_path:
            Path to presentation_plan.json.

        output_path:
            Destination .pptx path.

        template_path:
            Optional PowerPoint template.

        image_root:
            Optional root directory containing extracted images.

        clear_template_slides:
            If True, remove example/content slides from the template
            before generating the presentation.

    Returns:
        Absolute path to generated PowerPoint.
    """

    plan_path = os.path.abspath(plan_path)

    output_path = os.path.abspath(output_path)

    # ---------------------------------------------------------------
    # Load plan.
    # ---------------------------------------------------------------

    plan = load_presentation_plan(
        plan_path
    )

    # ---------------------------------------------------------------
    # Validate plan.
    # ---------------------------------------------------------------

    problems = validate_plan_for_generation(
        plan
    )

    if problems:

        for problem in problems:
            print(f"Warning: {problem}")

    # ---------------------------------------------------------------
    # Load PowerPoint template.
    # ---------------------------------------------------------------

    prs = load_template(
        template_path
    )

    # ---------------------------------------------------------------
    # Remove template example slides if requested.
    # ---------------------------------------------------------------

    if clear_template_slides:
        remove_existing_slides(prs)

    # ---------------------------------------------------------------
    # Build image lookup.
    # ---------------------------------------------------------------

    image_catalog = build_image_catalog(
        plan
    )

    # ---------------------------------------------------------------
    # Generate slides.
    # ---------------------------------------------------------------

    slides = plan["slides"]

    print(
        f"Generating {len(slides)} slides..."
    )

    for index, slide_plan in enumerate(
        slides,
        start=1,
    ):

        if not isinstance(slide_plan, dict):

            print(
                f"Warning: Skipping invalid slide {index}."
            )

            continue

        try:

            render_slide(
                prs=prs,
                slide_plan=slide_plan,
                image_catalog=image_catalog,
                plan_path=plan_path,
                image_root=image_root,
            )

            print(
                f"  Created slide {index}: "
                f"{get_slide_title(slide_plan)}"
            )

        except Exception as exc:

            print(
                f"Warning: Could not render slide "
                f"{index}: {exc}"
            )

    # ---------------------------------------------------------------
    # Ensure output directory exists.
    # ---------------------------------------------------------------

    output_directory = Path(
        output_path
    ).parent

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ---------------------------------------------------------------
    # Save presentation.
    # ---------------------------------------------------------------

    prs.save(output_path)

    print(
        f"\nPresentation saved to:\n"
        f"{output_path}"
    )

    return output_path


# ---------------------------------------------------------------------------
# COMMAND LINE INTERFACE
# ---------------------------------------------------------------------------

def main():
    """
    Command-line interface.

    Example:

        python ppt_generator.py \
            presentation_plan.json \
            output.pptx \
            --template template.pptx \
            --image-root images/
    """

    parser = argparse.ArgumentParser(
        description=(
            "Generate a PowerPoint presentation from "
            "presentation_plan.json."
        )
    )

    parser.add_argument(
        "plan",
        help="Path to presentation_plan.json",
    )

    parser.add_argument(
        "output",
        help="Path for generated .pptx",
    )

    parser.add_argument(
        "--template",
        default=None,
        help="Optional PowerPoint template (.pptx/.potx)",
    )

    parser.add_argument(
        "--image-root",
        default=None,
        help=(
            "Optional root directory containing "
            "extracted PDF images."
        ),
    )

    parser.add_argument(
        "--keep-template-slides",
        action="store_true",
        help=(
            "Keep existing slides from the PowerPoint template."
        ),
    )

    args = parser.parse_args()

    generate_presentation(
        plan_path=args.plan,
        output_path=args.output,
        template_path=args.template,
        image_root=args.image_root,
        clear_template_slides=not args.keep_template_slides,
    )


if __name__ == "__main__":
    main()