def get_blank_layout(
    prs: Presentation,
):
    """
    Find the blank layout in the template.

    Falls back to the first available layout.
    """

    for layout in prs.slide_layouts:

        name = (layout.name or "").lower()

        if "blank" in name:
            return layout

    if prs.slide_layouts:
        return prs.slide_layouts[0]

    raise ValueError(
        "Presentation template contains no slide layouts."
    )


def add_blank_slide(
    prs: Presentation,
):
    """
    Add a blank slide while preserving the template's theme.
    """

    layout = get_blank_layout(prs)

    return prs.slides.add_slide(layout)


def get_slide_dimensions(
    prs: Presentation,
) -> Tuple[float, float]:
    """
    Return slide dimensions in inches.
    """

    width = prs.slide_width / 914400
    height = prs.slide_height / 914400

    return width, height


