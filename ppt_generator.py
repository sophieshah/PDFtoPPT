def load_template(
    template_path: Optional[str] = None,
) -> Presentation:
    """
    Load a PowerPoint template.

    If no template is provided, create a blank presentation.

    Args:
        template_path:
            Optional .pptx/.potx file.

    Returns:
        python-pptx Presentation object.
    """

    if template_path:

        template_path = os.path.abspath(template_path)

        if not os.path.exists(template_path):
            raise FileNotFoundError(
                f"PowerPoint template not found: {template_path}"
            )

        return Presentation(template_path)

    # Blank presentation.
    prs = Presentation()

    prs.slide_width = Inches(DEFAULT_WIDTH)
    prs.slide_height = Inches(DEFAULT_HEIGHT)

    return prs


def remove_existing_slides(
    prs: Presentation,
) -> None:
    """
    Remove all existing slides from the presentation.

    This is useful when the supplied template contains example slides
    that should not appear in the final presentation.

    NOTE:
        This preserves the presentation's slide layouts/theme.
    """

    slide_ids = list(prs.slides._sldIdLst)

    for slide_id in slide_ids:

        r_id = slide_id.rId

        prs.part.drop_rel(r_id)

        prs.slides._sldIdLst.remove(slide_id)


